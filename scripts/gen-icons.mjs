const ATTRS = {
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-width": "strokeWidth",
  "stroke-miterlimit": "strokeMiterlimit",
  "stroke-dasharray": "strokeDasharray",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "fill-opacity": "fillOpacity",
  "stroke-opacity": "strokeOpacity",
};

function inner(file) {
  const svg = fs.readFileSync(`${DIR}${file}_light.svg`, "utf8");
  let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  if (/<(defs|clipPath|mask|linearGradient|style)/.test(body)) throw new Error(`${file}: unsupported element`);
  body = body.replace(/(stroke|fill)="#[0-9a-fA-F]{3,8}"/g, '$1="currentColor"');
  for (const [k, v] of Object.entries(ATTRS)) body = body.replaceAll(`${k}=`, `${v}=`);
  body = body.replace(/<(path|circle|rect|ellipse|line|polyline|polygon)([^>]*?)\s*\/?>(<\/\1>)?/g, "<$1$2 />");
  if (/[a-z]+-[a-z]+=/.test(body)) throw new Error(`${file}: unconverted attribute in ${body}`);
  return body.replace(/\n/g, "");
}

const parts = [];
for (const [name, file] of Object.entries(MAP)) parts.push([name, inner(file), file]);
for (const [name, body] of Object.entries(CUSTOM)) parts.push([name, body, "custom"]);
for (const [name, [file, deg]] of Object.entries(ROTATED)) parts.push([name, `<g transform="rotate(${deg} 12 12)">${inner(file)}</g>`, `${file}, rotated`]);
parts.sort((a, b) => a[0].localeCompare(b[0]));

