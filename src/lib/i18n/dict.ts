export const DICTS: Record<Lang, Record<DictKey, string>> = { uz, ru };

export function translate(lang: Lang, key: DictKey | string, vars?: Record<string, string | number>): string {
  const d = DICTS[lang] as Record<string, string>;
  let s = d[key] ?? (DICTS.uz as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export type I18nText = { uz: string; ru?: string | null } | null | undefined;

/** Picks a translation from a {uz, ru} object, falling back to Uzbek. */
export function tr(v: I18nText, lang: Lang): string {
  if (!v) return "";
  return (lang === "ru" && v.ru) || v.uz || "";
}

export function isLang(v: unknown): v is Lang {
  return v === "uz" || v === "ru";
}
